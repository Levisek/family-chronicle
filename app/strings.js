  function pick() {
    let saved = null;
    try { saved = g.localStorage.getItem('fc-lang'); } catch (e) { /* storage off */ }
    if (saved && strings[saved]) return saved;
    const nav = String((g.navigator && g.navigator.language) || 'en').slice(0, 2).toLowerCase();
    return strings[nav] ? nav : 'en';
  }

  const FCApp = (g.FCApp = g.FCApp || {});
  FCApp.strings = strings;
  FCApp.lang = pick();
  FCApp.setLang = (lang) => {
    if (!strings[lang]) return;
    FCApp.lang = lang;
    try { g.localStorage.setItem('fc-lang', lang); } catch (e) { /* storage off */ }
  };
  FCApp.t = (key, vars = {}) => {
    const s = (strings[FCApp.lang] && strings[FCApp.lang][key]) ?? strings.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (all, k) => (k in vars ? String(vars[k]) : all));
  };
