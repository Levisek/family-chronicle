// Writes app/data/gazetteer.js (window.FC_GAZ, read by engine/gazetteer.js) from a GeoNames dump.
// Place names: GeoNames (https://www.geonames.org), CC BY 4.0.
//
// Get the files from https://download.geonames.org/export/dump/ into one folder and unzip them:
//   cities500.zip, alternateNamesV2.zip, admin1CodesASCII.txt, countryInfo.txt and one <CC>.zip for
//   every country in VILLAGES below (unzip -o <file>.zip -d <folder>).
// Run: node tools/gazetteer.mjs <folder>
//
// Content: every town of cities500 (population 500 and more, worldwide) plus every populated place
// (feature class P) of the countries in VILLAGES, where most villages of the ancestors of the first
// users lie; alternate names in LANGS (and those without a language). Budget: 25 MB.
import { createReadStream, readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const VILLAGES = ['CZ', 'SK', 'AT', 'HU', 'PL', 'RS', 'BG', 'RO', 'HR', 'SI', 'UA'];
const LANGS = new Set(['de', 'hu', 'pl', 'cs', 'sk', 'la', 'it', 'en', '']);
const SKIP_LANGS = new Set(['link', 'post', 'iata', 'icao', 'faac', 'abbr', 'wkdt', 'unlc', 'fr_1793']);
const UI_LANGS = readdirSync(join(ROOT, 'locales')).filter((n) => n.endsWith('.json')).map((n) => n.slice(0, -5)).sort();

// the same as normalize() in engine/gazetteer.js, without the house-number rules
const norm = (s) => s.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/\s+/g, ' ').trim();
const round = (x) => Math.round(parseFloat(x) * 1e4) / 1e4;

async function* lines(path) {
  const rl = createInterface({ input: createReadStream(path, 'utf8'), crlfDelay: Infinity });
  for await (const line of rl) if (line && !line.startsWith('#')) yield line.split('\t');
}

async function main(dir) {
  const places = new Map();   // geonameid -> [name, lat, lon, cc, admin1]
  const take = async (file, onlyP) => {
    for await (const p of lines(join(dir, file))) {
      if (onlyP && p[6] !== 'P') continue;
      if (!places.has(p[0])) places.set(p[0], [p[1], round(p[4]), round(p[5]), p[8], p[10]]);
    }
  };
  await take('cities500.txt', false);
  for (const cc of VILLAGES) await take(`${cc}.txt`, true);

  const admin1 = new Map();   // geonameid -> code; code -> [display, names...]
  const admin1Names = {};
  for (const p of readFileSync(join(dir, 'admin1CodesASCII.txt'), 'utf8').split('\n')) {
    const c = p.split('\t');
    if (c.length < 4) continue;
    admin1.set(c[3], c[0]);
    admin1Names[c[0]] = [c[1], ...new Set([norm(c[1]), norm(c[2])])];
  }
  const country = new Map();  // geonameid -> cc
  const countries = {}, countryNames = {};
  for (const line of readFileSync(join(dir, 'countryInfo.txt'), 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const c = line.split('\t');
    country.set(c[16], c[0]);
    countries[norm(c[4])] = c[0];
    countryNames[c[0]] = { en: c[4] };
  }

  const alt = new Map();      // geonameid of a place -> [names]
  const preferred = new Set();
  for await (const p of lines(join(dir, 'alternateNamesV2.txt'))) {
    const [, id, lang, name, isPreferred, isShort] = p;
    if (SKIP_LANGS.has(lang) || !name) continue;
    if (places.has(id)) {
      if (!LANGS.has(lang)) continue;
      const a = alt.get(id);
      if (a) a.push(name); else alt.set(id, [name]);
    } else if (admin1.has(id)) {
      if (!LANGS.has(lang)) continue;
      const names = admin1Names[admin1.get(id)];
      const k = norm(name);
      if (!names.includes(k)) names.push(k);
    } else if (country.has(id)) {
      const cc = country.get(id);
      if (LANGS.has(lang)) countries[norm(name)] = countries[norm(name)] || cc;
      if (UI_LANGS.includes(lang) && lang !== 'en' && isShort !== '1') {
        const key = `${cc}.${lang}`;
        if (isPreferred === '1' && !preferred.has(key)) { countryNames[cc][lang] = name; preferred.add(key); }
        else if (!countryNames[cc][lang]) countryNames[cc][lang] = name;
      }
    }
  }

  const rows = [];
  const index = new Map();
  for (const [id, row] of places) {
    const i = rows.length;
    rows.push(row);
    const seen = new Set([norm(row[0])]);
    for (const name of alt.get(id) || []) {
      const k = norm(name);
      if (!k || seen.has(k)) continue;
      seen.add(k);
      const a = index.get(k);
      if (a) a.push(i); else index.set(k, [i]);
    }
  }
  const sortedObj = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
  const out = [
    '// Generated by tools/gazetteer.mjs from GeoNames (https://www.geonames.org, CC BY 4.0); do not edit.',
    'window.FC_GAZ = {names: [',
    rows.map((r) => JSON.stringify(r)).join(',\n'),
    '], index: ' + JSON.stringify(Object.fromEntries([...index.keys()].sort().map((k) => [k, index.get(k)]))) + ',',
    'admin1: ' + JSON.stringify(sortedObj(admin1Names)) + ',',
    'countries: ' + JSON.stringify(sortedObj(countries)) + ',',
    'countryNames: ' + JSON.stringify(sortedObj(countryNames)) + '};',
    '',
  ].join('\n');
  const path = join(ROOT, 'app/data/gazetteer.js');
  writeFileSync(path, out);
  console.log(`${rows.length} places, ${index.size} alternate names, ${(statSync(path).size / 1e6).toFixed(1)} MB`);
}

if (!process.argv[2]) { console.error('usage: node tools/gazetteer.mjs <folder with the unzipped GeoNames files>'); process.exit(2); }
await main(process.argv[2]);
