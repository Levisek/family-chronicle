// Writes engine/templates.js from templates/*.html (the HTML files stay the source).
// Run: node tools/make-templates.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../templates/', import.meta.url);
const names = readdirSync(dir).filter((f) => f.endsWith('.html')).sort();
const table = Object.fromEntries(names.map((n) => [n.replace(/\.html$/, ''), readFileSync(new URL(n, dir), 'utf8')]));
const out = `// Page templates (generated by tools/make-templates.mjs from templates/*.html; do not edit).
// Python string.Template syntax: $name, \${name}, $$ for a dollar; a missing variable is an error.
(function (g) {
  'use strict';

  const TEMPLATES = ${JSON.stringify(table, null, 1)};

  const PATTERN = /\\$(?:(\\$)|([_a-z][_a-z0-9]*)|\\{([_a-z][_a-z0-9]*)\\}|())/gi;

  function substitute(template, vars) {
    return template.replace(PATTERN, (all, escaped, named, braced, invalid, offset) => {
      if (escaped !== undefined) return '$';
      const key = named || braced;
      if (key !== undefined) {
        if (!Object.prototype.hasOwnProperty.call(vars, key)) throw new Error(\`template variable missing: \${key}\`);
        return String(vars[key]);
      }
      throw new Error(\`invalid placeholder in template at \${offset}\`);
    });
  }

  const api = { TEMPLATES, substitute };
  for (const name of Object.keys(TEMPLATES)) api[name] = (vars) => substitute(TEMPLATES[name], vars);
  if (typeof module !== 'undefined') module.exports = api;
  else (g.FCEngine = g.FCEngine || {}).templates = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;
writeFileSync(new URL('../engine/templates.js', import.meta.url), out);
