// Writes app/data/world.js (window.FC_WORLD, read by engine/basemap.js): the Natural Earth 50m
// layers of familychronicle/basemap.py for the whole world, coordinates rounded to 3 decimals.
// Natural Earth is public domain (naturalearthdata.com).
// Get the files from https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
// (ne_50m_land, ne_50m_lakes, ne_50m_admin_0_boundary_lines_land, ne_50m_rivers_lake_centerlines,
// each .geojson) into one folder.
// Run: node tools/world.mjs <folder>
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const LAYERS = { land: 'ne_50m_land', lakes: 'ne_50m_lakes', borders: 'ne_50m_admin_0_boundary_lines_land', rivers: 'ne_50m_rivers_lake_centerlines' };
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/world.mjs <folder with the Natural Earth .geojson files>'); process.exit(2); }

const rnd = (c) => (typeof c[0] === 'number' ? [Number(c[0].toFixed(3)) || 0, Number(c[1].toFixed(3)) || 0] : c.map(rnd));
// the part after "window.FC_WORLD = " is JSON (tests/golden/make_golden.py reads it)
const layers = Object.entries(LAYERS).map(([layer, stem]) => {
  const gj = JSON.parse(readFileSync(join(dir, `${stem}.geojson`), 'utf8'));
  const geoms = gj.features.filter((f) => f.geometry).map((f) => ({ type: f.geometry.type, coordinates: rnd(f.geometry.coordinates) }));
  return `${JSON.stringify(layer)}: [\n${geoms.map((x) => JSON.stringify(x)).join(',\n')}\n]`;
});
const lines = ['// Generated by tools/world.mjs from Natural Earth 50m (public domain); do not edit.', `window.FC_WORLD = {${layers.join(',\n')}};`, ''];
const path = join(ROOT, 'app/data/world.js');
writeFileSync(path, lines.join('\n'));
console.log(`${(statSync(path).size / 1e6).toFixed(1)} MB`);
